import React, { useState } from 'react';
import { useNavigate } from 'react-router-dom';
import {
  Shield,
  Package,
  ShoppingBag,
  DollarSign,
  Plus,
  Edit2,
  Trash2,
  LogOut,
  Sparkles,
  TrendingUp,
  Zap,
  Star,
  RefreshCw,
  Search,
  Check
} from 'lucide-react';
import { useProducts } from '../hooks/useProducts';
import { useAuth } from '../hooks/useAuth';
import StatCard from '../components/StatCard';
import AdminProductForm from '../components/AdminProductForm';
import { formatPrice } from '../utils/formatPrice';

export default function Admin() {
  const {
    products,
    orders,
    addProduct,
    updateProduct,
    deleteProduct,
    updateStock,
    resetToDefaultProducts
  } = useProducts();
  const { logout } = useAuth();
  const navigate = useNavigate();

  const [activeTab, setActiveTab] = useState('products'); // 'products', 'orders', 'featured'
  const [editingProduct, setEditingProduct] = useState(null);
  const [isAddingNew, setIsAddingNew] = useState(false);
  const [searchQuery, setSearchQuery] = useState('');

  const totalProducts = products.length;
  const totalOrders = orders.length;
  const totalRevenue = orders.reduce((sum, order) => sum + (order.totalAmount || 0), 0);

  const handleLogout = () => {
    logout();
    navigate('/admin-login');
  };

  const handleSaveProduct = (productData) => {
    if (editingProduct) {
      updateProduct(editingProduct.id, productData);
      setEditingProduct(null);
    } else {
      addProduct(productData);
      setIsAddingNew(false);
    }
  };

  const filteredProducts = products.filter(p =>
    p.name.toLowerCase().includes(searchQuery.toLowerCase()) ||
    p.category.toLowerCase().includes(searchQuery.toLowerCase()) ||
    p.platform.toLowerCase().includes(searchQuery.toLowerCase())
  );

  return (
    <div className="space-y-8 pb-16">
      {/* Top Bar Header */}
      <div className="bg-[#080d1f] border border-slate-800 rounded-2xl p-6 flex flex-col md:flex-row md:items-center justify-between gap-4">
        <div>
          <div className="flex items-center space-x-2">
            <Shield className="w-6 h-6 text-cyan-400" />
            <h1 className="text-2xl font-black text-white">Dano Store Management Dashboard</h1>
          </div>
          <p className="text-xs text-slate-400 mt-1">
            Manage inventory, update stocks, view customer orders, and toggle home sections.
          </p>
        </div>

        <div className="flex items-center space-x-3">
          <button
            onClick={resetToDefaultProducts}
            className="px-3.5 py-2 rounded-xl bg-slate-900 border border-slate-800 text-slate-400 hover:text-white text-xs font-semibold flex items-center space-x-1.5"
            title="Reset catalog to initial preset"
          >
            <RefreshCw className="w-3.5 h-3.5" />
            <span>Reset Products</span>
          </button>

          <button
            onClick={handleLogout}
            className="px-4 py-2 rounded-xl bg-red-500/10 border border-red-500/30 text-red-400 hover:bg-red-500/20 text-xs font-bold flex items-center space-x-1.5"
          >
            <LogOut className="w-4 h-4" />
            <span>Logout</span>
          </button>
        </div>
      </div>

      {/* Analytics Overview Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-4">
        <StatCard
          title="Total Products"
          value={totalProducts}
          subtitle="Active items in store catalog"
          icon={Package}
          color="cyan"
        />
        <StatCard
          title="Total Customer Orders"
          value={totalOrders}
          subtitle="Orders generated by visitors"
          icon={ShoppingBag}
          color="blue"
        />
        <StatCard
          title="Total Revenue Generated"
          value={formatPrice(totalRevenue)}
          subtitle="Sum of completed & pending orders"
          icon={DollarSign}
          color="emerald"
        />
      </div>

      {/* Navigation Tabs */}
      <div className="flex items-center space-x-2 border-b border-slate-800 pb-2">
        <button
          onClick={() => { setActiveTab('products'); setIsAddingNew(false); setEditingProduct(null); }}
          className={`px-4 py-2 rounded-xl text-xs font-bold transition-all ${
            activeTab === 'products'
              ? 'bg-cyan-500/20 text-cyan-400 border border-cyan-500/40'
              : 'text-slate-400 hover:text-slate-200'
          }`}
        >
          Product Catalog ({totalProducts})
        </button>
        <button
          onClick={() => { setActiveTab('orders'); setIsAddingNew(false); setEditingProduct(null); }}
          className={`px-4 py-2 rounded-xl text-xs font-bold transition-all ${
            activeTab === 'orders'
              ? 'bg-cyan-500/20 text-cyan-400 border border-cyan-500/40'
              : 'text-slate-400 hover:text-slate-200'
          }`}
        >
          Customer Orders ({totalOrders})
        </button>
        <button
          onClick={() => { setActiveTab('sections'); setIsAddingNew(false); setEditingProduct(null); }}
          className={`px-4 py-2 rounded-xl text-xs font-bold transition-all ${
            activeTab === 'sections'
              ? 'bg-cyan-500/20 text-cyan-400 border border-cyan-500/40'
              : 'text-slate-400 hover:text-slate-200'
          }`}
        >
          Manage Home Sections
        </button>
      </div>

      {/* Content Area */}
      {activeTab === 'products' && (
        <div className="space-y-6">

          {/* Add or Edit Form Drawer */}
          {(isAddingNew || editingProduct) && (
            <AdminProductForm
              initialData={editingProduct}
              onSubmit={handleSaveProduct}
              onCancel={() => { setIsAddingNew(false); setEditingProduct(null); }}
            />
          )}

          {/* Product List Controls */}
          {!isAddingNew && !editingProduct && (
            <div className="bg-[#080d1e] border border-slate-800 rounded-2xl p-4 flex flex-col sm:flex-row items-center justify-between gap-4">
              <div className="relative w-full sm:w-72">
                <Search className="w-4 h-4 text-slate-500 absolute left-3 top-1/2 -translate-y-1/2" />
                <input
                  type="text"
                  placeholder="Search admin products..."
                  value={searchQuery}
                  onChange={(e) => setSearchQuery(e.target.value)}
                  className="w-full bg-[#0d1326] border border-slate-800 rounded-xl py-2 pl-9 pr-3 text-xs text-white outline-none"
                />
              </div>

              <button
                onClick={() => setIsAddingNew(true)}
                className="w-full sm:w-auto px-5 py-2.5 rounded-xl bg-gradient-to-r from-blue-600 to-cyan-500 text-black font-extrabold text-xs flex items-center justify-center space-x-1.5 shadow-md shadow-cyan-500/20"
              >
                <Plus className="w-4 h-4" />
                <span>Add New Product</span>
              </button>
            </div>
          )}

          {/* Products Table */}
          {!isAddingNew && !editingProduct && (
            <div className="bg-[#080d1e] border border-slate-800 rounded-2xl overflow-hidden">
              <div className="overflow-x-auto">
                <table className="w-full text-left text-xs text-slate-300">
                  <thead className="bg-[#0c1228] text-slate-400 uppercase tracking-wider font-bold border-b border-slate-800">
                    <tr>
                      <th className="p-4">Product</th>
                      <th className="p-4">Category</th>
                      <th className="p-4">Platform</th>
                      <th className="p-4">Price (IQD)</th>
                      <th className="p-4">Stock</th>
                      <th className="p-4 text-right">Actions</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-800/60">
                    {filteredProducts.map((p) => (
                      <tr key={p.id} className="hover:bg-slate-900/50">
                        <td className="p-4">
                          <div className="font-bold text-white">{p.name}</div>
                          <span className="text-[10px] text-cyan-400">{p.type} • {p.packages?.length || 1} Pkgs</span>
                        </td>
                        <td className="p-4 uppercase text-[11px] font-semibold text-slate-400">{p.category}</td>
                        <td className="p-4 font-semibold text-slate-300">{p.platform}</td>
                        <td className="p-4 font-bold text-cyan-400">{formatPrice(p.price)}</td>
                        <td className="p-4">
                          <input
                            type="number"
                            value={p.stock}
                            onChange={(e) => updateStock(p.id, e.target.value)}
                            className="w-20 bg-[#0d1326] border border-slate-800 rounded-lg py-1 px-2 text-xs text-white outline-none font-bold"
                          />
                        </td>
                        <td className="p-4 text-right space-x-2">
                          <button
                            onClick={() => setEditingProduct(p)}
                            className="p-1.5 rounded-lg bg-slate-900 text-cyan-400 hover:bg-slate-800"
                            title="Edit Product"
                          >
                            <Edit2 className="w-4 h-4" />
                          </button>
                          <button
                            onClick={() => {
                              if (confirm(`Delete product ${p.name}?`)) {
                                deleteProduct(p.id);
                              }
                            }}
                            className="p-1.5 rounded-lg bg-slate-900 text-red-400 hover:bg-slate-800"
                            title="Delete Product"
                          >
                            <Trash2 className="w-4 h-4" />
                          </button>
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </div>
          )}

        </div>
      )}

      {/* Orders Tab */}
      {activeTab === 'orders' && (
        <div className="space-y-4">
          <div className="bg-[#080d1e] border border-slate-800 rounded-2xl overflow-hidden">
            {orders.length === 0 ? (
              <div className="py-16 text-center space-y-2">
                <ShoppingBag className="w-10 h-10 text-slate-600 mx-auto" />
                <h3 className="text-sm font-bold text-white">No customer orders yet</h3>
                <p className="text-xs text-slate-400">Orders placed by customers will be displayed here.</p>
              </div>
            ) : (
              <div className="overflow-x-auto">
                <table className="w-full text-left text-xs text-slate-300">
                  <thead className="bg-[#0c1228] text-slate-400 uppercase tracking-wider font-bold border-b border-slate-800">
                    <tr>
                      <th className="p-4">Order ID</th>
                      <th className="p-4">Customer</th>
                      <th className="p-4">Phone / City</th>
                      <th className="p-4">Payment Method</th>
                      <th className="p-4">Items</th>
                      <th className="p-4">Total Amount</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-800/60">
                    {orders.map((o) => (
                      <tr key={o.orderId} className="hover:bg-slate-900/50">
                        <td className="p-4 font-black text-cyan-400">{o.orderId}</td>
                        <td className="p-4 font-bold text-white">{o.customerName}</td>
                        <td className="p-4">
                          <div>{o.phoneNumber}</div>
                          <span className="text-[10px] text-slate-400">{o.city}</span>
                        </td>
                        <td className="p-4">
                          <span className="px-2.5 py-1 rounded bg-slate-900 border border-slate-800 text-cyan-400 font-bold uppercase text-[10px]">
                            {o.paymentMethod}
                          </span>
                        </td>
                        <td className="p-4">
                          <div className="space-y-1">
                            {o.items?.map((item, idx) => (
                              <div key={idx} className="text-[11px]">
                                • {item.name} ({item.packageName}) x{item.quantity}
                              </div>
                            ))}
                          </div>
                        </td>
                        <td className="p-4 font-black text-emerald-400">{formatPrice(o.totalAmount)}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            )}
          </div>
        </div>
      )}

      {/* Section Flag Toggles Tab */}
      {activeTab === 'sections' && (
        <div className="bg-[#080d1e] border border-slate-800 rounded-2xl p-6 space-y-4">
          <h3 className="text-base font-bold text-white">Manage Product Flags for Home Sections</h3>
          <p className="text-xs text-slate-400">Toggle which products show up in Featured, Trending, Flash Deals, or Top Rated.</p>

          <div className="divide-y divide-slate-800">
            {products.map(p => (
              <div key={p.id} className="py-3 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 text-xs">
                <div>
                  <span className="font-bold text-white">{p.name}</span>
                  <span className="text-slate-400 ml-2">({p.platform})</span>
                </div>

                <div className="flex flex-wrap gap-2">
                  <button
                    onClick={() => updateProduct(p.id, { isFeatured: !p.isFeatured })}
                    className={`px-2.5 py-1 rounded-lg font-bold border transition-all ${
                      p.isFeatured ? 'bg-cyan-500/20 text-cyan-400 border-cyan-500/40' : 'bg-slate-900 text-slate-500 border-slate-800'
                    }`}
                  >
                    Featured
                  </button>

                  <button
                    onClick={() => updateProduct(p.id, { isTrending: !p.isTrending })}
                    className={`px-2.5 py-1 rounded-lg font-bold border transition-all ${
                      p.isTrending ? 'bg-blue-500/20 text-blue-400 border-blue-500/40' : 'bg-slate-900 text-slate-500 border-slate-800'
                    }`}
                  >
                    Trending
                  </button>

                  <button
                    onClick={() => updateProduct(p.id, { isFlashDeal: !p.isFlashDeal })}
                    className={`px-2.5 py-1 rounded-lg font-bold border transition-all ${
                      p.isFlashDeal ? 'bg-purple-500/20 text-purple-400 border-purple-500/40' : 'bg-slate-900 text-slate-500 border-slate-800'
                    }`}
                  >
                    Flash Deal
                  </button>

                  <button
                    onClick={() => updateProduct(p.id, { isTopRated: !p.isTopRated })}
                    className={`px-2.5 py-1 rounded-lg font-bold border transition-all ${
                      p.isTopRated ? 'bg-amber-500/20 text-amber-400 border-amber-500/40' : 'bg-slate-900 text-slate-500 border-slate-800'
                    }`}
                  >
                    Top Rated
                  </button>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}

    </div>
  );
}
